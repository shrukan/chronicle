"""
Voice actor's script: the flavour text of every voiced page (the pages the original app has
voice-over for), from strings.en.json, one clip per page and reading mode. The clip names are the
ones the app plays, so a recording replaces the generated clip of the same name in
content/assets/audio/voice/<voice>/. Writes content/voice-script/<scenario>.md, which is
committed: regenerate it after editing a voiced text (`--check` fails while it is out of date).

Spoiler-free output: only counts are printed.

Usage: python3 tools/voice/script.py [--check]
"""

import argparse
import json
import re
import sys

import pages
from pages import CONTENT, ROOT

OUT = CONTENT / "voice-script"
INTROS = json.loads((ROOT / "tools" / "voice" / "voices.json").read_text())["intros"]


def placeholder(arg: dict) -> str:
    """A value filled in during play; a random pick from fixed words lists them, to record each."""
    if "var" in arg:
        return f"⟨{arg['var']}⟩"
    options = arg.get("args", [])
    if arg.get("fn") == "either" and all("lit" in o for o in options):
        return "⟨one of: " + " | ".join(str(o["lit"]) for o in options) + "⟩"
    if arg.get("fn") == "random" and all("lit" in o for o in options):
        return f"⟨number {options[0]['lit']}–{options[1]['lit']}⟩"
    return "⟨value⟩"


def readable(text: str, args: list[dict]) -> str:
    """String-table markup (engine/src/text.ts) for reading: emphasis kept, icons and values named."""
    text = re.sub(r"\{icon:([^}]*)\}", r"[\1]", text)
    return re.sub(r"\{(\d+)\}", lambda m: placeholder(args[int(m[1])]) if int(m[1]) < len(args) else "⟨value⟩", text)


def script(scenario_id: str) -> tuple[str, dict[str, int]]:
    folder = CONTENT / scenario_id
    scenario = json.loads((folder / "scenario.json").read_text())
    strings = json.loads((folder / "strings.en.json").read_text())
    counts = {"pages": 0, "clips": 0, "words": 0}
    md = [
        f"# Voice script: {scenario['id']}",
        "",
        "<!-- Generated by tools/voice/script.py from strings.en.json; do not edit. -->",
        "",
        "The voiced pages, one clip per page and version (Original, and Easy and Short where they",
        "differ). Record each clip as one file with the name given. **Bold** and *italic* are the",
        "app's emphasis; a blank line is a paragraph break; ⟨…⟩ is a name or value decided at the",
        "table.",
        "",
    ]
    for number, name in enumerate(pages.voiced(scenario_id, INTROS.get(scenario_id)), 1):
        passage = scenario["passages"][name]
        args = pages.args(passage)
        counts["pages"] += 1
        md += [f"## Page {number}: {name}", ""]
        for mode, paragraphs in pages.texts(passage, strings).items():
            words = sum(len(re.findall(r"\w+", re.sub(r"\{[^}]*\}", "", p))) for p in paragraphs)
            md += [f"### {mode.capitalize()} · `{pages.clip(name, mode)}` · {words} words", ""]
            for i, paragraph in enumerate(paragraphs):
                md += ([">"] if i else []) + [f"> {line}".rstrip() for line in readable(paragraph, args[i]).split("\n")]
            md.append("")
            counts["clips"] += 1
            counts["words"] += words
    return "\n".join(md), counts


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if a committed script is out of date")
    check = parser.parse_args().check
    stale = []
    for scenario_id in sorted(p.parent.name for p in CONTENT.glob("*/scenario.json")):
        text, counts = script(scenario_id)
        target = OUT / f"{scenario_id}.md"
        if check:
            if not target.exists() or target.read_text() != text:
                stale.append(scenario_id)
            continue
        OUT.mkdir(exist_ok=True)
        target.write_text(text)
        print(f"{scenario_id}: {counts['pages']} pages, {counts['clips']} clips, "
              f"{counts['words']:,} words ≈ {counts['words'] / 150:.0f} min")  # about 150 spoken words a minute
    if stale:
        sys.exit(f"voice script out of date ({', '.join(stale)}): run task content:voices:script")
    if not check:
        print(f"→ {OUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
